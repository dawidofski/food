export const ALLERGEN_TAGS: Record<string, string[]> = { ...CATEGORY_ALLERGENS, ...FOOD_ALLERGENS };

const has = (table: object, key: string): boolean => Object.prototype.hasOwnProperty.call(table, key);

/** Flags for a WWEIA category code. Unknown codes get the generic fallback. */
export function classifyByFoodGroup(code: string): ClassificationFlags {
  return has(GROUP_DEFAULTS, code) ? { ...GENERIC_FALLBACK, ...GROUP_DEFAULTS[code] } : { ...GENERIC_FALLBACK };
}

/** Group default, then the food's own override on top (override wins). */
export function classifyFood(foodCode: string, categoryCode: string): ClassificationFlags {
  const base = classifyByFoodGroup(categoryCode);
  return has(OVERRIDES, foodCode) ? { ...base, ...OVERRIDES[foodCode] } : base;
}

/** Union of the category's tags and the food's own tags, in EU_ALLERGENS order, no duplicates. */
export function allergensFor(foodCode: string, categoryCode: string): string[] {
  const tags = new Set<string>([
    ...(has(ALLERGEN_TAGS, categoryCode) ? (ALLERGEN_TAGS[categoryCode] ?? []) : []),
    ...(has(ALLERGEN_TAGS, foodCode) ? (ALLERGEN_TAGS[foodCode] ?? []) : []),
  ]);
  return EU_ALLERGENS.filter((a) => tags.has(a));
}
