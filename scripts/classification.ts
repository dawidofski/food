/**
 * Curated classification layer. USDA does not provide these flags, so they are authored here.
 *
 * Data only: three tables and three lookups. No parsing, no inference at build time.
 *   GROUP_DEFAULTS   WWEIA food category code (food.csv `food_category_id`) -> flags for the whole group
 *   OVERRIDES        FNDDS 8-digit food code -> flags that replace the group default (override wins)
 *   ALLERGEN_TAGS    WWEIA category code or FNDDS food code -> EU allergen groups (additive, see allergensFor)
 *
 * Honesty rules baked into the defaults:
 *  - A flag is only `true` when the group (or the named food) clearly is that thing. When unsure the
 *    flag stays false: the rule engine stays silent on an unflagged food, which is the safe direction.
 *  - redMeat means fresh/unprocessed red meat (beef, pork, lamb, goat, game, offal). Cured and
 *    processed meats are flagged processedMeat only, so intake is not double counted.
 *  - processedMeat = cured, salted, smoked or otherwise preserved meat (hot dogs, bacon, ham, salami,
 *    sausages, cold cuts, jerky, corned beef). Fresh cuts are not processed meat.
 *  - sweetDrink = sugar-sweetened soft/fruit/energy drinks. 100% juice, milk drinks and diet drinks are not.
 *  - novaGroup at group level is an approximation: a category cannot tell homemade from industrial.
 *  - Allergen tags are indicative and category/name derived. An ABSENT tag is NOT a guarantee that a
 *    food is free of that allergen; never present this as allergy-safety information.
 *
 * Food-code entries in OVERRIDES and ALLERGEN_TAGS were produced by matching USDA descriptions
 * (rules noted per block) and reviewed; they are committed as static data.
 */
